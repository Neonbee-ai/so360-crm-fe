import React, { useState, useEffect, useRef, useCallback } from 'react';
import { Loader2, Briefcase, Search } from 'lucide-react';
import { crmService, dealsApi } from '../../services/crmService';
import { Deal, DealStage, User, SalesRep } from '../../types/crm';
import { toast, Button, TextField, Select, NumberInput, DatePicker, Checkbox } from '@so360/design-system';
import { Modal } from '../../components/common/Modal';
import { useActivity } from '@so360/shell-context';
import { useCRMCurrencySymbol } from '../../utils/formatters';

interface CreateDealModalProps {
    leadId?: string;
    leadName?: string;
    companyName?: string;
    onClose: () => void;
    onSuccess: (deal: Deal) => void;
}


const CreateDealModal: React.FC<CreateDealModalProps> = ({ leadId, leadName, companyName = '', onClose, onSuccess }) => {
    const { recordActivity } = useActivity();
    const currencySymbol = useCRMCurrencySymbol();

    // Sales Rep options come from People Connect's People Registry via crm-be
    // (see crmService.getSalesReps). Calling People Connect straight from the
    // browser required people-module permissions a CRM user does not hold, so
    // the dropdown always resolved to an empty list.
    const [salesReps, setSalesReps] = useState<SalesRep[]>([]);
    const [salesRepsError, setSalesRepsError] = useState(false);
    // Distinct from "empty": before the first response lands there is nothing
    // to report yet, and claiming the registry is empty at that point is the
    // exact false alarm this field was reported for.
    const [salesRepsLoading, setSalesRepsLoading] = useState(true);
    const [salesRepSearch, setSalesRepSearch] = useState('');

    const loadSalesReps = useCallback(async () => {
        setSalesRepsError(false);
        setSalesRepsLoading(true);
        try {
            const reps = await crmService.getSalesReps();
            setSalesReps(
                [...reps].sort((a, b) => (a.full_name || '').localeCompare(b.full_name || '')),
            );
        } catch {
            setSalesReps([]);
            setSalesRepsError(true);
        } finally {
            setSalesRepsLoading(false);
        }
    }, []);

    useEffect(() => { loadSalesReps(); }, [loadSalesReps]);

    // Filtered client-side across every displayed attribute, so searching by
    // designation or department works even though the registry API only
    // indexes name/email/employee id.
    const visibleSalesReps = salesReps.filter((p) => {
        const q = salesRepSearch.trim().toLowerCase();
        if (!q) return true;
        return [p.full_name, p.email, p.employee_id, p.job_title, p.department_name]
            .some((v) => (v || '').toLowerCase().includes(q));
    });

    // Core fields
    const [name, setName] = useState('');
    const [isNameAutoGenerated, setIsNameAutoGenerated] = useState(false);
    const [namingEnabled, setNamingEnabled] = useState(false);
    const hasUserEditedName = useRef(false);
    const [value, setValue] = useState<string>('');
    const [stage, setStage] = useState<DealStage>('Lead');
    const [startDate, setStartDate] = useState<string>('');
    const [expectedClose, setExpectedClose] = useState<string>('');
    const [ownerId, setOwnerId] = useState<string>('');
    const [ownerPersonId, setOwnerPersonId] = useState<string>('');
    const hasUserPickedSalesRep = useRef(false);
    const [users, setUsers] = useState<User[]>([]);
    const [isSubmitting, setIsSubmitting] = useState(false);
    const [settings, setSettings] = useState<{ id: string; name: string }[]>([]);

    // Custom fields
    const [customFieldDefs, setCustomFieldDefs] = useState<any[]>([]);
    const [customFieldValues, setCustomFieldValues] = useState<Record<string, any>>({});

    // Customer search (Pipeline mode — no leadId provided)
    const [customerSearch, setCustomerSearch] = useState('');
    const [customerResults, setCustomerResults] = useState<any[]>([]);
    const [customerDropdownOpen, setCustomerDropdownOpen] = useState(false);
    const [selectedCompanyName, setSelectedCompanyName] = useState(companyName);
    const [selectedLeadId, setSelectedLeadId] = useState(leadId || '');
    const [companyError, setCompanyError] = useState('');
    const searchRef = useRef<HTMLDivElement>(null);
    const searchTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

    // Close customer dropdown on outside click
    useEffect(() => {
        const handleClick = (e: MouseEvent) => {
            if (searchRef.current && !searchRef.current.contains(e.target as Node)) {
                setCustomerDropdownOpen(false);
            }
        };
        document.addEventListener('mousedown', handleClick);
        return () => document.removeEventListener('mousedown', handleClick);
    }, []);

    // Debounced customer search
    useEffect(() => {
        if (leadId || customerSearch.length < 1) {
            setCustomerResults([]);
            setCustomerDropdownOpen(false);
            return;
        }
        if (searchTimerRef.current) clearTimeout(searchTimerRef.current);
        searchTimerRef.current = setTimeout(async () => {
            try {
                const results = await crmService.getCustomers({ q: customerSearch, take: 8 });
                setCustomerResults(results);
                setCustomerDropdownOpen(results.length > 0);
            } catch {
                setCustomerResults([]);
            }
        }, 300);
        return () => { if (searchTimerRef.current) clearTimeout(searchTimerRef.current); };
    }, [customerSearch, leadId]);

    useEffect(() => {
        const fetchDependencies = async () => {
            const [usersData, settingsData] = await Promise.all([
                crmService.getUsers(),
                crmService.getSettings()
            ]);
            setUsers(usersData);
            if (usersData.length > 0) setOwnerId(usersData[0].id);
            setSettings(settingsData.deal_stages);
            if (settingsData.deal_stages.length > 0) {
                setStage(settingsData.deal_stages[0].name as DealStage);
            }
            setCustomFieldDefs(settingsData.deal_custom_fields || []);
            setNamingEnabled(settingsData.deal_naming?.enabled ?? false);
        };
        fetchDependencies();
    }, []);

    const effectiveCompany = selectedCompanyName || companyName || '';
    const effectiveLeadId = selectedLeadId || leadId;

    // Lead → Deal carries the lead's Sales Rep forward, but only while that
    // person is still an active People Registry employee — an inactive rep must
    // not be silently re-assigned onto a brand new deal. The user can always
    // override, and their choice is never overwritten by this prefill.
    useEffect(() => {
        if (!effectiveLeadId || !salesReps.length || hasUserPickedSalesRep.current) return;
        let cancelled = false;
        crmService.getLeadById(effectiveLeadId).then(lead => {
            const leadPersonId = (lead as any)?.owner_person_id;
            if (cancelled || !leadPersonId || hasUserPickedSalesRep.current) return;
            if (salesReps.some(p => p.id === leadPersonId)) setOwnerPersonId(leadPersonId);
        }).catch(() => {
            // Prefill is a convenience — never blocks deal creation.
        });
        return () => { cancelled = true; };
    }, [effectiveLeadId, salesReps]);
    // A deal linked to a Lead doesn't need a company name — leads may
    // represent individual customers without an organization.
    const effectiveCompanyForSubmit = effectiveCompany || (effectiveLeadId ? leadName || '' : '');

    // Auto-generate the Deal Name from the org's naming convention whenever the
    // lead/company/owner context is available, as long as the org has
    // auto-generation enabled and the user hasn't manually edited the name yet.
    // Org has auto-generation disabled: never auto-fill, field stays manual-only.
    useEffect(() => {
        if (!namingEnabled || hasUserEditedName.current) return;
        if (!effectiveCompany && !effectiveLeadId) return;
        let cancelled = false;
        dealsApi.generateName({
            leadId: effectiveLeadId || undefined,
            companyName: effectiveCompany || undefined,
            ownerId: ownerId || undefined,
        }).then(result => {
            if (cancelled || hasUserEditedName.current) return;
            if (result.isAutoGenerated) {
                setName(result.name);
                setIsNameAutoGenerated(true);
            }
        }).catch(() => {
            // Fall back silently — never blocks deal creation.
        });
        return () => { cancelled = true; };
    }, [namingEnabled, effectiveCompany, effectiveLeadId, ownerId]);

    const handleSubmit = async (e: React.FormEvent) => {
        e.preventDefault();
        if (!effectiveLeadId && !effectiveCompany.trim()) {
            setCompanyError('Please select a customer or enter a company name.');
            return;
        }
        setCompanyError('');
        setIsSubmitting(true);
        try {
            const deal = await dealsApi.create({
                name,
                company: effectiveCompanyForSubmit,
                value: parseFloat(value) || 0,
                stage_id: settings.find(s => s.name === stage)?.id || stage,
                owner_id: ownerId,
                owner_person_id: ownerPersonId || undefined,
                start_date: startDate ? new Date(startDate).toISOString() : undefined,
                expected_close: expectedClose ? new Date(expectedClose).toISOString() : undefined,
                lead_id: effectiveLeadId || undefined,
                custom_fields: Object.keys(customFieldValues).length > 0 ? customFieldValues : undefined,
                is_name_auto_generated: isNameAutoGenerated,
            });
            recordActivity({
                eventType: 'deal.created',
                eventCategory: 'crm',
                description: `Created deal "${name}" for ${effectiveCompanyForSubmit}`,
                resourceType: 'deal',
                resourceId: deal?.id,
            }).catch(() => {});
            onSuccess(deal);
            onClose();
        } catch (error) {
            console.error('Failed to create deal', error);
            toast.error(error instanceof Error && error.message ? error.message : 'Failed to create deal');
        } finally {
            setIsSubmitting(false);
        }
    };

    const renderCustomField = (field: any) => {
        const fieldId = field.id;
        const val = customFieldValues[fieldId];
        const type = (field.type || field.field_type || 'text').toLowerCase();
        const setVal = (v: any) => setCustomFieldValues(prev => ({ ...prev, [fieldId]: v }));

        if (type === 'boolean') {
            return (
                <Checkbox
                    key={fieldId}
                    name={`deal-cf-${fieldId}`}
                    label={field.label}
                    checked={!!val}
                    onChange={(e: React.ChangeEvent<HTMLInputElement>) => setVal(e.target.checked)}
                />
            );
        }

        if (type === 'select') {
            const opts: string[] = field.options || [];
            return (
                <Select
                    key={fieldId}
                    name={`deal-cf-${fieldId}`}
                    label={field.label}
                    value={val || ''}
                    onChange={(e: React.ChangeEvent<HTMLSelectElement>) => setVal(e.target.value)}
                    options={[{ value: '', label: 'Select…' }, ...opts.map(o => ({ value: o, label: o }))]}
                />
            );
        }

        if (type === 'number') {
            return (
                <NumberInput
                    key={fieldId}
                    name={`deal-cf-${fieldId}`}
                    label={field.label}
                    value={val === undefined || val === null || val === '' ? null : Number(val)}
                    onChange={(v: number | null) => setVal(v === null ? '' : String(v))}
                />
            );
        }

        if (type === 'date') {
            return (
                <DatePicker
                    key={fieldId}
                    name={`deal-cf-${fieldId}`}
                    label={field.label}
                    value={val || ''}
                    onChange={(v: string) => setVal(v)}
                />
            );
        }

        return (
            <TextField
                key={fieldId}
                name={`deal-cf-${fieldId}`}
                label={field.label}
                type="text"
                value={val || ''}
                onChange={(e: React.ChangeEvent<HTMLInputElement>) => setVal(e.target.value)}
            />
        );
    };

    return (
        <Modal
            isOpen
            onClose={onClose}
            size="lg"
            dismissible={!isSubmitting}
            data-testid="create-deal-modal"
            title={
                <span className="flex items-center gap-2">
                    <Briefcase className="text-primary" size={24} />
                    New Deal
                </span>
            }
            footer={
                <>
                    <Button type="button" variant="secondary" onClick={onClose} disabled={isSubmitting}>
                        Cancel
                    </Button>
                    <Button type="submit" form="create-deal-form" variant="primary" disabled={isSubmitting}>
                        {isSubmitting && <Loader2 size={12} className="animate-spin" />}
                        Create Deal
                    </Button>
                </>
            }
        >
                    <form id="create-deal-form" onSubmit={handleSubmit} className="flex flex-col">
                        <div className="space-y-5">
                            {leadId && companyError && (
                                <p className="text-xs text-danger font-bold">{companyError}</p>
                            )}
                            {/* Customer / Company (Pipeline mode only) */}
                            {!leadId && (
                                <div className="relative" ref={searchRef}>
                                    <TextField
                                        name="deal-customer-search"
                                        label="Customer / Company *"
                                        type="text"
                                        leadingIcon={Search}
                                        value={selectedCompanyName || customerSearch}
                                        onChange={(e: React.ChangeEvent<HTMLInputElement>) => {
                                            setSelectedCompanyName('');
                                            setSelectedLeadId('');
                                            setCustomerSearch(e.target.value);
                                            setCompanyError('');
                                        }}
                                        placeholder="Search customer or type company name…"
                                        error={companyError || undefined}
                                    />
                                    {customerDropdownOpen && customerResults.length > 0 && (
                                        <div className="absolute top-full left-0 right-0 mt-1 bg-surface border border-line rounded-nb-lg shadow-xl z-menu overflow-hidden">
                                            {customerResults.map(c => (
                                                <button
                                                    key={c.id}
                                                    type="button"
                                                    onClick={() => {
                                                        const selectedName = c.company_name || c.contact_name || c.name || '';
                                                        setSelectedCompanyName(selectedName);
                                                        setSelectedLeadId(c.id);
                                                        setCustomerSearch('');
                                                        setCustomerDropdownOpen(false);
                                                        setCompanyError('');
                                                        // Auto-generate effect re-fires from the effectiveCompany/
                                                        // effectiveLeadId change above — no manual fallback needed here.
                                                    }}
                                                    className="w-full text-left px-4 py-2.5 hover:bg-surface-raised transition-colors border-b border-line last:border-0"
                                                >
                                                    <div className="text-sm font-bold text-fg">{c.company_name || c.contact_name || c.name}</div>
                                                    {c.contact_email && <div className="text-xs text-fg-muted">{c.contact_email}</div>}
                                                </button>
                                            ))}
                                        </div>
                                    )}
                                </div>
                            )}

                            {/* Deal Name */}
                            <TextField
                                name="deal-name"
                                label="Deal Name"
                                type="text"
                                value={name}
                                onChange={(e: React.ChangeEvent<HTMLInputElement>) => {
                                    hasUserEditedName.current = true;
                                    setIsNameAutoGenerated(false);
                                    setName(e.target.value);
                                }}
                                required
                            />

                            {/* Value + Stage */}
                            <div className="grid grid-cols-1 wc-medium:grid-cols-2 gap-nb-3">
                                <div className="flex items-end gap-nb-2">
                                    <span className="pb-3 text-fg-muted text-xs font-bold select-none">{currencySymbol}</span>
                                    <div className="flex-1 min-w-0">
                                        <NumberInput
                                            name="deal-value"
                                            label="Value"
                                            value={value === '' ? null : Number(value)}
                                            onChange={(v: number | null) => setValue(v === null ? '' : String(v))}
                                            required
                                            min={0}
                                        />
                                    </div>
                                </div>
                                <Select
                                    name="deal-stage"
                                    label="Stage"
                                    value={stage}
                                    onChange={(e: React.ChangeEvent<HTMLSelectElement>) => setStage(e.target.value as DealStage)}
                                    options={settings.map(s => ({ value: s.name, label: s.name }))}
                                />
                            </div>

                            {/* Dates */}
                            <div className="grid grid-cols-1 wc-medium:grid-cols-2 gap-nb-3">
                                <DatePicker
                                    name="deal-start-date"
                                    label="Start Date"
                                    value={startDate}
                                    onChange={(v: string) => setStartDate(v)}
                                />
                                <DatePicker
                                    name="deal-close-date"
                                    label="Close Date"
                                    value={expectedClose}
                                    onChange={(v: string) => setExpectedClose(v)}
                                />
                            </div>

                            {/* Owner */}
                            <Select
                                name="deal-owner"
                                label="Owner (User)"
                                value={ownerId}
                                onChange={(e: React.ChangeEvent<HTMLSelectElement>) => setOwnerId(e.target.value)}
                                options={users.map(u => ({ value: u.id, label: u.full_name }))}
                            />

                            {/* Sales Rep */}
                            <div className="space-y-2">
                                {salesReps.length > 8 && (
                                    <TextField
                                        name="deal-sales-rep-search"
                                        aria-label="Search sales reps"
                                        type="text"
                                        leadingIcon={Search}
                                        size="sm"
                                        value={salesRepSearch}
                                        onChange={(e: React.ChangeEvent<HTMLInputElement>) => setSalesRepSearch(e.target.value)}
                                        placeholder="Search by name, email, designation or department…"
                                    />
                                )}
                                <Select
                                    name="deal-sales-rep"
                                    label="Sales Rep (optional)"
                                    value={ownerPersonId}
                                    onChange={(e: React.ChangeEvent<HTMLSelectElement>) => { hasUserPickedSalesRep.current = true; setOwnerPersonId(e.target.value); }}
                                    options={[
                                        { value: '', label: 'Select sales rep...' },
                                        ...visibleSalesReps.map((p) => ({
                                            value: p.id,
                                            label: `${p.full_name}${p.job_title ? ` — ${p.job_title}` : ''}${p.department_name ? ` · ${p.department_name}` : ''}`,
                                        })),
                                    ]}
                                />
                                {/* Never fail silently: an empty registry and a failed
                                    fetch look identical in a bare <select>. */}
                                {salesRepsLoading ? (
                                    <p className="text-xs font-bold text-fg-muted flex items-center gap-1.5">
                                        <Loader2 size={10} className="animate-spin" />
                                        Loading employees...
                                    </p>
                                ) : salesRepsError ? (
                                    <p className="text-xs font-bold text-danger">
                                        Could not load employees from People Connect.{' '}
                                        <button type="button" onClick={loadSalesReps} className="underline hover:text-danger-300">
                                            Retry
                                        </button>
                                    </p>
                                ) : salesReps.length === 0 ? (
                                    <p className="text-xs font-bold text-fg-muted">
                                        No active employees found in People Connect → People Registry.
                                    </p>
                                ) : null}
                            </div>

                            {/* Custom fields */}
                            {customFieldDefs.length > 0 && (
                                <div className="border-t border-line pt-5 space-y-5">
                                    <p className="text-xs font-semibold text-fg-muted">Additional Information</p>
                                    {customFieldDefs.map(f => renderCustomField(f))}
                                </div>
                            )}
                        </div>

                    </form>
        </Modal>
    );
};

export default CreateDealModal;
